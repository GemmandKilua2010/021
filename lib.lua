			Config.CloseAnimTime
		})

		if Parts.Icon then
			CreateTween({
				Parts.Icon,
				"ImageTransparency",
				1,
				Config.CloseAnimTime
			})
		end

		task.delay(Config.CloseAnimTime * 0.4, function()
			if not Slot or not Slot.Parent then
				if Callback then
					Callback()
				end
				return
			end

			local CollapseTween = TweenService:Create(
				Slot,
				TweenInfo.new(
					Config.CloseAnimTime,
					Enum.EasingStyle.Quad,
					Enum.EasingDirection.In
				),
