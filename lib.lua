			-- Nenhuma thumbnail é buscada aqui.
			local InitialPlayers = {}

			for _, Player in ipairs(Players:GetPlayers()) do
				local PlayerData = CreatePlayerDataIfValid(Player)

				if PlayerData then
					table.insert(InitialPlayers, PlayerData)
				end
			end

