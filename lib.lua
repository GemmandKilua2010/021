					return Selected
				end

				if type(Selected) == "table" and Selected.Player then
					return Selected.Player
				end

				for Player, Data in pairs(PlayerOptions) do
					if Data.Name == Selected
						or Data.UserName == Selected
						or Data.DisplayName == Selected then
						return Player
					end
				end

				return nil
