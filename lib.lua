	local function GetNotificationScale()
		local Camera = workspace.CurrentCamera
		if not Camera then
			return 1
		end

		local ShortSide = math.min(Camera.ViewportSize.X, Camera.ViewportSize.Y)

		if IsNotificationTenFoot() then
